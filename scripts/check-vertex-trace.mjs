import assert from 'node:assert/strict';
import { traceVertexBody, vertexTransportError } from '../lib/vertex-response-trace.ts';
const encoder = new TextEncoder();
const events = [];
const emit = (event, fields) => events.push({ event, ...fields });
const input = encoder.encode('data: 中文\n\n');
const output = await new Response(traceVertexBody(new ReadableStream({ start(c) { c.enqueue(input.subarray(0,9)); c.enqueue(input.subarray(9)); c.close(); } }), emit)).arrayBuffer();
assert.deepEqual(new Uint8Array(output),input);
assert.deepEqual(events,[{event:'body_end',bytes:input.length}]);
console.log('PASS: normal EOF preserves split UTF-8 bytes');
events.length=0;
let source;
const broken = traceVertexBody(new ReadableStream({start(c){source=c;}}),emit).getReader();
source.enqueue(encoder.encode('partial'));
await broken.read();
const error = Object.assign(new TypeError('secret payload'),{cause:{code:'UND_ERR_SOCKET'}});
source.error(error);
await assert.rejects(broken.read(),e=>e===error);
assert.deepEqual(events,[{event:'body_error',bytes:7,errorName:'TypeError',errorCode:'UND_ERR_SOCKET'}]);
console.log('PASS: body error remains an error; no sensitive message logged');
events.length=0;
let cancelled;
const pending=traceVertexBody(new ReadableStream({cancel(r){cancelled=r;}}),emit).getReader();
const read=pending.read();
await pending.cancel('user cancellation');
await read;
assert.equal(cancelled,'user cancellation');
assert.deepEqual(events,[{event:'body_cancel',bytes:0}]);
assert.deepEqual(vertexTransportError({name:'https://secret',code:'private key'}),{errorName:'unknown',errorCode:'unknown'});
console.log('PASS: cancellation propagates, unsafe error metadata removed');
